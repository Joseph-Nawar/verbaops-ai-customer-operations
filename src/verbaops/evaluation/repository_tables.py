"""SQLAlchemy Core table definitions shared by the evaluation repository."""

from sqlalchemy import (
    Boolean,
    Column,
    DateTime,
    Float,
    ForeignKey,
    Integer,
    MetaData,
    String,
    Table,
    UniqueConstraint,
)
from sqlalchemy.dialects.postgresql import JSONB, UUID

metadata = MetaData()
eval_runs = Table(
    "eval_runs",
    metadata,
    Column("id", UUID(as_uuid=True), primary_key=True),
    Column("dataset_version", String(255), nullable=False),
    Column("dataset_sha256", String(64), nullable=False),
    Column("git_sha", String(255), nullable=False),
    Column("environment", String(255), nullable=False),
    Column("capability_alias", String(128), nullable=False),
    Column("gateway_model_id", String(512)),
    Column("model", String(512)),
    Column("provider", String(255)),
    Column("prompt_version", String(255), nullable=False),
    Column("graph_version", String(255), nullable=False),
    Column("tool_schema_version", String(255), nullable=False),
    Column("started_at", DateTime(timezone=True), nullable=False),
    Column("completed_at", DateTime(timezone=True)),
    Column("status", String(32), nullable=False),
    Column("case_count", Integer, nullable=False),
    Column("summary_json", JSONB),
    Column("latency_ms", Float),
    Column("cost_usd", Float),
)
eval_results = Table(
    "eval_results",
    metadata,
    Column("id", UUID(as_uuid=True), primary_key=True),
    Column("eval_run_id", UUID(as_uuid=True), ForeignKey("eval_runs.id", ondelete="CASCADE"), nullable=False),
    Column("case_id", String(255), nullable=False),
    Column("split", String(32), nullable=False),
    Column("category", String(128), nullable=False),
    Column("language", String(16), nullable=False),
    Column("passed", Boolean, nullable=False),
    Column("expected_tool", String(128)),
    Column("observed_tools", JSONB, nullable=False),
    Column("expected_arguments", JSONB, nullable=False),
    Column("observed_arguments", JSONB, nullable=False),
    Column("expected_outcome", JSONB, nullable=False),
    Column("observed_outcome", JSONB, nullable=False),
    Column("metric_details", JSONB, nullable=False),
    Column("failure_reasons", JSONB, nullable=False),
    Column("latency_ms", Float),
    Column("cost_usd", Float),
    Column("agent_run_id", UUID(as_uuid=True), ForeignKey("agent_runs.id", ondelete="SET NULL")),
    Column("created_at", DateTime(timezone=True), nullable=False),
    UniqueConstraint("eval_run_id", "case_id", name="uq_eval_results_run_case"),
)
